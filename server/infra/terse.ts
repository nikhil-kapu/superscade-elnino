// Terse durable actors: one ResponderAgent actor per spawned agent, one ResourceLedger actor per run.
// Every call is short-timeout + fire-and-forget safe: if Terse isn't reachable the sim keeps running (logged once).
// Start the actor runtime with:  cd actors && bunx terse-cli@latest actor dev   (serves http://127.0.0.1:7100)
import { emit } from '../bus.ts';

const TIMEOUT_MS = Number(process.env.TERSE_TIMEOUT_MS) || 5000;
const ACTOR_URL = process.env.TERSE_ACTOR_URL || 'http://127.0.0.1:7100/v1/projects/local/actors';
const DISABLED = process.env.TERSE_DISABLED === '1';

type Pool = Record<string, number>;
export interface ClaimResult { granted: number; requested: number; resource: string; remaining: number; status: 'granted' | 'partial' | 'denied'; claimNo: number }

let mod: any = null;
let up: boolean | null = null;
let warned = false;
let lastCheck = 0;

async function client(): Promise<any> {
  if (mod) return mod;
  // generated by `terse actor generate` in actors/ (runs fine under Node: plain fetch transport)
  const path = '../../actors/generated/index.js';
  mod = await import(/* @vite-ignore */ path);
  return mod;
}

function warnOnce(msg: string) {
  if (warned) return; warned = true;
  console.warn(`[terse] ${msg} — durable actors disabled until reachable (run: cd actors && bunx terse-cli@latest actor dev)`);
  emit({ type: 'log', level: 'warn', text: `[terse] ${msg}; continuing without durable actors` });
}

function withTimeout<T>(p: Promise<T>, ms = TIMEOUT_MS): Promise<T> {
  return Promise.race([p, new Promise<T>((_, rej) => setTimeout(() => rej(new Error(`terse timeout ${ms}ms`)), ms))]);
}

/** cheap reachability probe, cached for 10s */
export async function isTerseUp(): Promise<boolean> {
  if (DISABLED) return false;
  if (up !== null && Date.now() - lastCheck < 10_000) return up;
  lastCheck = Date.now();
  try {
    const base = new URL(ACTOR_URL); // any HTTP answer from the dev server counts as up
    await withTimeout(fetch(`${base.origin}/`, { method: 'GET' }), 800);
    await client();
    if (up === false) { console.log('[terse] reachable again'); warned = false; }
    up = true;
  } catch (e: any) {
    up = false;
    warnOnce(`not reachable at ${ACTOR_URL} (${e?.message ?? e})`);
  }
  return up;
}

async function call<T>(fn: (actors: any) => Promise<T>): Promise<T | null> {
  if (!(await isTerseUp())) return null;
  try { const m = await client(); return await withTimeout(fn(m.actors)); }
  catch (e: any) { warnOnce(`call failed: ${e?.message ?? e}`); return null; }
}

export async function bootAgent(info: { agentId: string; runId: string; role: string; label: string; districtId?: string; model?: string; parentId?: string }): Promise<boolean> {
  const t0 = Date.now();
  const r = await call(a => a.ResponderAgent.get(info.agentId).boot({ runId: info.runId, role: info.role, label: info.label, districtId: info.districtId, model: info.model, parentId: info.parentId }));
  if (r) emit({ type: 'terse.actor', runId: info.runId, agentId: info.agentId, actor: `ResponderAgent/${info.agentId}`, ok: true, ms: Date.now() - t0 });
  return !!r;
}

export function agentStatus(agentId: string, status: string, note?: string): void {
  void call(a => a.ResponderAgent.get(agentId).setStatus(status, note ?? ''));
}

export function agentRemember(agentId: string, kind: string, text: string, tick?: number, from?: string): void {
  void call(a => a.ResponderAgent.get(agentId).remember(kind, text, tick ?? 0, from ?? 'self'));
}

export async function agentRecall(agentId: string, limit = 10): Promise<{ tick: number; kind: string; text: string; from: string }[]> {
  return (await call(a => a.ResponderAgent.get(agentId).recall(limit))) ?? [];
}

export async function initLedger(runId: string, regionId: string, pool?: Pool): Promise<Pool | null> {
  return call(a => a.ResourceLedger.get(runId).init(regionId, pool));
}

export async function claimResources(runId: string, agentId: string, districtId: string, resource: string, qty: number): Promise<ClaimResult | null> {
  if (qty <= 0) return null;
  const r = await call<ClaimResult>(a => a.ResourceLedger.get(runId).claim(agentId, districtId, resource, qty));
  if (r) {
    const led = await call<any>(a => a.ResourceLedger.get(runId).getLedger(1));
    emit({ type: 'terse.claim', runId, agentId, districtId, resource, requested: r.requested, granted: r.granted, status: r.status, remaining: led?.remaining ?? { [resource]: r.remaining }, total: led?.total });
  }
  return r;
}

export async function getLedger(runId: string): Promise<any | null> {
  return call(a => a.ResourceLedger.get(runId).getLedger(30));
}

export async function releaseResources(runId: string, agentId: string, districtId: string, resource: string, qty: number): Promise<number | null> {
  if (qty <= 0) return null;
  const left = await call<number>(a => a.ResourceLedger.get(runId).release(agentId, districtId, resource, qty));
  if (left !== null) {
    const led = await call<any>(a => a.ResourceLedger.get(runId).getLedger(1));
    emit({ type: 'terse.claim', runId, agentId, districtId, resource, requested: qty, granted: qty, status: 'released', remaining: led?.remaining ?? { [resource]: left }, total: led?.total });
  }
  return left;
}
